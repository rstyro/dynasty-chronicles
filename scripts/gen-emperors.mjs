/**
 * 生成单个帝王的 markdown 文件内容
 * @param {Object} data - 帝王数据对象
 * @returns {string} 完整的 markdown 文件内容
 */
function generateContent(data) {
  // 身份字段：默认"皇帝"，特殊人物（如慈禧太后）另行标注
  const identity = data.identity || '皇帝'

  // 构建 frontmatter
  const fm = [
    '---',
    `title: ${data.name}`,
    `dynasty: ${data.dynasty}`,
    `type: emperor`,
    `era: ${data.era}`,
    `order: ${data.order}`,
    '---'
  ].join('\n')

  // 构建基本信息表
  const infoRows = [
    `| **姓名** | ${data.fullName} |`,
    `| **生卒** | ${data.years} |`,
    `| **朝代** | [${data.dynastyName}](${data.dynastyLink}) |`,
    `| **身份** | ${identity} |`,
    `| **在位** | ${data.reign} |`
  ]

  // 构建功绩列表
  const achievementLines = data.achievements.map(a => `- **${a}**`)

  // 构建参考资料列表
  const referenceLines = data.references.map(r => `- ${r}`)

  // 组装完整内容
  return [
    fm,
    '',
    `# ${data.name}`,
    '',
    `> **${data.quote}**`,
    '',
    '---',
    '',
    '## 📋 基本信息',
    '',
    '| 项目 | 内容 |',
    '|------|------|',
    ...infoRows,
    '',
    '---',
    '',
    '## 📖 生平概述',
    '',
    data.bio,
    '',
    '---',
    '',
    '## 🏛️ 主要功绩',
    '',
    ...achievementLines,
    '',
    '---',
    '',
    '## 🔗 相关链接',
    '',
    `- [${data.dynastyName}](${data.dynastyLink})`,
    '',
    '---',
    '',
    '## 📖 参考资料',
    '',
    ...referenceLines,
    ''
  ].join('\n')
}

// ── 主流程 ──────────────────────────────────────────────────

// 确保目录存在
if (!fs.existsSync(emperorsDir)) {
  fs.mkdirSync(emperorsDir, { recursive: true })
}

let created = 0, skipped = 0

// 遍历帝王数据，逐个生成文件
for (const data of EMPERORS) {
  const filePath = path.join(emperorsDir, `${data.slug}.md`)

  // 已存在则跳过，不覆盖已有文件
  if (fs.existsSync(filePath)) {
    console.log(`  ⏭️  ${data.slug}.md 已存在，跳过`)
    skipped++
    continue
  }

  // 生成并写入文件
  const content = generateContent(data)
  fs.writeFileSync(filePath, content, 'utf-8')
  console.log(`  ✏️  ${data.slug}.md → ${data.name}（${data.era}）`)
  created++
}

