/**
 * 生成单个谋臣的 markdown 内容
 * @param {Object} data - 谋臣数据对象
 * @returns {string} 完整的 markdown 文件内容
 */
function generateContent(data) {
  // 构建 frontmatter
  const fm = [
    '---',
    `title: ${data.name}`,
    `dynasty: 三国`,
    `type: strategist`,
    `era: ${data.faction}`,
    '---'
  ].join('\n')

  // 构建基本信息表
  const infoRows = [
    `| **姓名** | ${data.name}${data.style !== '不详' ? `（字${data.style}）` : ''} |`,
    `| **生卒** | ${data.years} |`,
    `| **朝代** | [三国·${data.faction}](/dynasties/sanguo) |`,
    `| **身份** | 谋臣 |`
  ]

  // 构建功绩列表
  const achievementLines = data.achievements.map(a => `- **${a}**`)

  // 组装完整内容
  return [
    fm,
    '',
    `# ${data.name}`,
    '',
    `> **${data.quote}**`,
    '',
    '---',
    '',
    '## 📋 基本信息',
    '',
    '| 项目 | 内容 |',
    '|------|------|',
    ...infoRows,
    '',
    '---',
    '',
    '## 📖 生平概述',
    '',
    data.bio,
    '',
    '---',
    '',
    '## 🏛️ 主要功绩',
    '',
    ...achievementLines,
    '',
    '---',
    '',
    '## 🔗 相关链接',
    '',
    '- [三国](/dynasties/sanguo)',
    '',
    '---',
    '',
    '## 📖 参考资料',
    '',
    '- 《三国志》',
    ''
  ].join('\n')
}

// ── 主流程 ──────────────────────────────────────────────────

// 确保目录存在
if (!fs.existsSync(strategistsDir)) {
  fs.mkdirSync(strategistsDir, { recursive: true })
}

let created = 0, skipped = 0

for (const data of STRATEGISTS) {
  const filePath = path.join(strategistsDir, `${data.slug}.md`)

  // 已存在则跳过
  if (fs.existsSync(filePath)) {
    console.log(`  ⏭️  ${data.slug}.md 已存在，跳过`)
    skipped++
    continue
  }

  // 生成并写入文件
  const content = generateContent(data)
  fs.writeFileSync(filePath, content, 'utf-8')
  console.log(`  ✏️  ${data.slug}.md → ${data.name}（${data.faction}）`)
  created++
}

