/** 生成单个北朝皇帝 markdown 内容 */
function generateContent(d) {
  const fm = [
    '---',
    `title: ${d.name}`,
    'dynasty: 两晋南北朝',
    'type: emperor',
    `era: ${d.era}`,
    `order: ${d.order}`,
    '---'
  ].join('\n')

  const infoRows = [
    `| **姓名** | ${d.fullName} |`,
    `| **生卒** | ${d.years} |`,
    `| **在位** | ${d.reign} |`,
    `| **朝代** | [${d.era.replace('-', '·')}](/dynasties/nanbei/beichao) |`,
    `| **庙号** | ${d.temple} |`,
    `| **谥号** | ${d.posthumous} |`,
    `| **主要成就** | ${d.achievement} |`
  ]

  const achievementLines = d.achievements.map(a => `- **${a}**`)
  const commentBlock = d.comment ? `\n---\n\n## 🗣️ 历史评价\n\n> ${d.comment}\n` : ''
  const linkLines = d.links.map(l => `- [${l}](${LINK_MAP[l] || '/dynasties/nanbei/beichao'})`)
  const refLines = d.refs.map(r => `- ${r}`)

  return [
    fm,
    '',
    `# ${d.name}`,
    '',
    `> **${d.quote}**`,
    '',
    '---',
    '',
    '## 📋 基本信息',
    '',
    '| 项目 | 内容 |',
    '|------|------|',
    ...infoRows,
    '',
    '---',
    '',
    '## 📖 生平概述',
    '',
    d.bio,
    '',
    '---',
    '',
    '## 🏛️ 主要功绩',
    '',
    ...achievementLines,
    commentBlock,
    '',
    '---',
    '',
    '## 🔗 相关链接',
    '',
    ...linkLines,
    '',
    '---',
    '',
    '## 📖 参考资料',
    '',
    ...refLines,
    ''
  ].join('\n')
}

