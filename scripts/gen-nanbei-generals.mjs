function generateContent(d) {
  const relLines = d.relations
    .map(([n, link, note]) => (link ? `- [${n}](${link}) — ${note}` : `- ${n} — ${note}`))
    .join('\n')

  return `---
title: ${d.name}
dynasty: 两晋南北朝
type: general
era: ${d.era}
---

# ${d.name}

> ${d.years} ｜ ${d.epithet}

---

## 📖 生平

${d.bio}

---

## ⚔️ 主要战绩

| 战役 | 对手 | 战果 |
|------|------|------|
${d.battles.map(([b, o, r]) => `| ${b} | ${o} | ${r} |`).join('\n')}

---

## 🔗 相关人物

${relLines}

---

## 📖 参考资料

${d.refs.map(r => `- ${r}`).join('\n')}
`
}

let count = 0
for (const d of GENERALS) {
  const filePath = path.join(outDir, `${d.slug}.md`)
  fs.writeFileSync(filePath, generateContent(d), 'utf-8')
  count++
  console.log(`✓ ${d.slug}.md（${d.name}，${d.era}）`)
}
console.log(`\n共生成 ${count} 个武将页面 → ${outDir}`)
