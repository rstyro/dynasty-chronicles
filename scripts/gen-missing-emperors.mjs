/**
 * 生成 markdown 内容
 * @param {Object} d
 * @returns {string}
 */
function gen(d) {
  return [
    '---',
    `title: ${d.title}`,
    `dynasty: ${d.dynasty}`,
    `type: emperor`,
    `era: ${d.era}`,
    `order: ${d.order}`,
    '---', '',
    `# ${d.title}${d.subtitle ? ' · ' + d.subtitle : ''}`, '',
    `> **${d.quote}**`, '',
    '---', '',
    '## 📋 基本信息', '',
    '| 项目 | 内容 |',
    '|------|------|',
    `| **姓名** | ${d.name} |`,
    `| **生卒** | ${d.life} |`,
    `| **在位** | ${d.reign} |`,
    `| **朝代** | ${d.dynastyLink} |`,
    `| **庙号** | ${d.miao || '—'} |`,
    `| **谥号** | ${d.shi || '—'} |`,
    `| **主要成就** | ${d.ach} |`,
    '',
    '---', '',
    '## 📖 生平概述', '',
    d.bio, '',
    '---', '',
    '## 🏛️ 主要功绩', '',
    ...d.achievements.map(a => `- **${a}**`),
    '',
    '---', '',
    '## 🗣️ 历史评价', '',
    `> ${d.eval}`, '',
    '---', '',
    '## 🔗 相关链接', '',
    ...d.links.map(l => `- ${l}`),
    '',
    '---', '',
    '## 📖 参考资料', '',
    '- 《史记》《竹书纪年》《汉书》《后汉书》《三国志》《晋书》《宋书》《南齐书》',
    '- 《梁书》《陈书》《魏书》《北齐书》《周书》《隋书》《旧唐书》《新唐书》《旧五代史》《宋史》',
    ''
  ].join('\n')
}

