/**
 * 生成单个帝王的 markdown 内容
 * @param {Object} d 帝王数据对象
 * @returns {string}
 */
function gen(d) {
  return [
    '---',
    `title: ${d.title}`,
    `dynasty: ${d.dynasty}`,
    `type: emperor`,
    `era: ${d.era}`,
    `order: ${d.order}`,
    '---', '',
    `# ${d.title}${d.subtitle ? ' · ' + d.subtitle : ''}`, '',
    `> **${d.quote}**`, '',
    '---', '',
    '## 📋 基本信息', '',
    '| 项目 | 内容 |',
    '|------|------|',
    `| **姓名** | ${d.name} |`,
    `| **生卒** | ${d.life} |`,
    `| **在位** | ${d.reign} |`,
    `| **朝代** | ${d.dynastyLink} |`,
    `| **庙号** | ${d.miao || '—'} |`,
    `| **谥号** | ${d.shi || '—'} |`,
    `| **主要成就** | ${d.ach} |`,
    '',
    '---', '',
    '## 📖 生平概述', '',
    d.bio, '',
    '---', '',
    '## 🏛️ 主要功绩', '',
    ...d.achievements.map(a => `- **${a}**`),
    '',
    '---', '',
    '## 🗣️ 历史评价', '',
    `> ${d.eval}`, '',
    '---', '',
    '## 🔗 相关链接', '',
    ...d.links.map(l => `- ${l}`),
    '',
    '---', '',
    '## 📖 参考资料', '',
    '- 《史记》/《后汉书》/《晋书》/《宋书》/《旧五代史》/《金史》/《明史》/《清史稿》',
    ''
  ].join('\n')
}

