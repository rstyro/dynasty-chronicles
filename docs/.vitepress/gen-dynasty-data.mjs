/**
 * 从 docs/dynasties 下各朝代页的 frontmatter 生成统一朝代数据，
 * 供时间线、时代坐标组件复用，避免时间线与总览页各维护一份。
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const docsDir = path.resolve(__dirname, '..')
const dynastyDir = path.join(docsDir, 'dynasties')
const outFile = path.join(docsDir, 'utils', 'dynasties.generated.js')

const PERIOD_ORDER = [
  '上古·文明起源',
  '东周·诸侯割据',
  '秦汉·大一统',
  '三国·两晋·十六国',
  '南北朝·民族融合',
  '隋唐盛世',
  '多民族政权并立',
  '大一统皇朝',
  '近代·共和转型',
  '当代·复兴之路'
]

const PERIOD_SLUGS = {
  '上古·文明起源': 'ancient',
  '东周·诸侯割据': 'dongzhou',
  '秦汉·大一统': 'qinhan',
  '三国·两晋·十六国': 'weijin',
  '南北朝·民族融合': 'nanbei',
  '隋唐盛世': 'suitang',
  '多民族政权并立': 'songliao',
  '大一统皇朝': 'imperial',
  '近代·共和转型': 'modern',
  '当代·复兴之路': 'contemporary'
}

// 总览页（父级）不进入时间轴，避免与子朝代重复计数
const OVERVIEW_SLUGS = new Set([
  'spring-autumn',
  'han',
  'sanguo',
  'jin',
  'nanbei-chao',
  'song'
])

// 政治主线：并立政权（蜀汉、孙吴、十六国、北朝、辽、西夏、金）不占主线位置
const MAIN_LINE = [
  'three-sovereigns', 'xia', 'shang', 'western-zhou',
  'chunqiu', 'zhanguo',
  'qin', 'chu-han', 'western-han', 'xin', 'eastern-han',
  'cao-wei', 'western-jin', 'eastern-jin', 'nanchao',
  'sui', 'tang', 'wudai-shiguo', 'northern-song', 'southern-song',
  'yuan', 'ming', 'qing', 'republic', 'prc'
]

const HIERARCHY = {
  'spring-autumn': ['chunqiu', 'zhanguo'],
  'han': ['western-han', 'xin', 'eastern-han'],
  'sanguo': ['cao-wei', 'shu-han', 'sun-wu'],
  'jin': ['western-jin', 'eastern-jin', 'sixteen-kingdoms'],
  'nanbei-chao': ['nanchao', 'beichao'],
  'song': ['northern-song', 'southern-song']
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name)
    return entry.isDirectory() ? walk(full) : [full]
  })
}

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return {}
  const result = {}
  match[1].split(/\r?\n/).forEach(line => {
    const colonIdx = line.indexOf(':')
    if (colonIdx <= 0) return
    const key = line.slice(0, colonIdx).trim()
    let value = line.slice(colonIdx + 1).trim()
    if ((value.startsWith("'") && value.endsWith("'")) ||
        (value.startsWith('"') && value.endsWith('"'))) {
      value = value.slice(1, -1)
    }
    result[key] = value
  })
  return result
}

function toYear(value) {
  if (!value || value === '传说时代') return null
  if (value === '今' || value === '至今') return new Date().getFullYear()
  if (/^前\d+$/.test(value)) return -Number(value.slice(1))
  const year = Number(value)
  return Number.isFinite(year) ? year : null
}

const entries = []
const bySlug = new Map()

for (const file of walk(dynastyDir)) {
  if (!file.endsWith('.md') || file.endsWith('index.md')) continue
  const slug = path.basename(file, '.md')
  const content = fs.readFileSync(file, 'utf-8')
  const fm = parseFrontmatter(content)
  if (!PERIOD_ORDER.includes(fm.period)) {
    throw new Error(`朝代页 ${file} 的 period 不在标准时期内：${fm.period}`)
  }
  const url = '/' + path.relative(docsDir, file).replace(/\\/g, '/').replace(/\.md$/, '')
  const entry = {
    slug,
    name: fm.title || slug,
    url,
    period: fm.period,
    start: fm.start || '',
    end: fm.end || '',
    startYear: toYear(fm.start),
    endYear: toYear(fm.end),
    capital: fm.capital || '—',
    founder: fm.founder || '—',
    last: fm.last || '—',
    keyword: fm.keyword || '',
    description: fm.description || ''
  }
  entries.push(entry)
  bySlug.set(slug, entry)
}

const byPeriod = new Map(PERIOD_ORDER.map(period => [period, []]))
for (const entry of entries) byPeriod.get(entry.period).push(entry)

const dynasties = []
for (const period of PERIOD_ORDER) {
  const items = byPeriod.get(period)
    .filter(entry => !OVERVIEW_SLUGS.has(entry.slug))
    .sort((a, b) => {
      const ay = a.startYear ?? -Infinity
      const by = b.startYear ?? -Infinity
      if (ay !== by) return ay - by
      return a.name.localeCompare(b.name, 'zh-CN')
    })
  dynasties.push(...items)
}

const mainLine = MAIN_LINE.map(slug => {
  const entry = bySlug.get(slug)
  if (!entry) throw new Error(`主线中的朝代页不存在：${slug}`)
  return entry.url
})

const overviewChildren = {}
for (const [parent, children] of Object.entries(HIERARCHY)) {
  const parentEntry = bySlug.get(parent)
  if (!parentEntry) continue
  overviewChildren[parentEntry.url] = children
    .map(slug => bySlug.get(slug))
    .filter(Boolean)
    .map(entry => entry.url)
}

const header = `// AUTO-GENERATED by docs/.vitepress/gen-dynasty-data.mjs — 请勿手工编辑。\n`

const body = [
  header,
  `export const periodOrder = ${JSON.stringify(PERIOD_ORDER, null, 2)}\n`,
  `export const periodSlugs = ${JSON.stringify(PERIOD_SLUGS, null, 2)}\n`,
  `export const dynasties = ${JSON.stringify(dynasties, null, 2)}\n`,
  `export const mainLine = ${JSON.stringify(mainLine, null, 2)}\n`,
  `export const overviewChildren = ${JSON.stringify(overviewChildren, null, 2)}\n`
].join('\n')

fs.writeFileSync(outFile, body, 'utf-8')
console.log(`生成 ${path.relative(docsDir, outFile)}：${dynasties.length} 个朝代，${Object.keys(overviewChildren).length} 个总览页`)
